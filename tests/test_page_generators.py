from __future__ import annotations

import json
import os
from pathlib import Path
from unittest.mock import patch

from pcide.core.api_center import ApiError, generate_client_module, validate_endpoint
from pcide.core.paths import Paths, node_runtime
from pcide.core.processes import run_bounded
from pcide.ui.platform_dialogs import atomic_files
from tests.test_core import WorkspaceCase


class PageGeneratorTests(WorkspaceCase):
    def test_http_methods_and_python_timeout_match_real_transport(self):
        self.assertEqual(validate_endpoint({'id': 'headers', 'name': '响应头', 'method': 'HEAD', 'path': '/'}).method, 'HEAD')
        with self.assertRaises(ApiError):
            validate_endpoint({'id': 'send', 'name': '发送', 'method': 'SEND', 'path': '/'})
        with self.assertRaisesRegex(ApiError, '60'):
            generate_client_module([{'id': 'slow', 'name': '超时', 'path': '/', 'timeout_seconds': 61}])

    def test_quoted_javascript_and_typescript_clients_execute_and_cancel_timeouts(self):
        node = node_runtime()
        if not node:
            self.skipTest('Node.js unavailable')
        compiler = Paths().resources / 'sdk/typescript/package/lib/typescript.js'
        self.assertTrue(compiler.is_file())
        endpoint = {'id': 'users.list', 'name': '用户', 'method': 'POST', 'path': '/users?name=\'"', 'timeout_seconds': .01}
        work = self.temp / 'clients'
        work.mkdir()
        for language in ('javascript', 'typescript'):
            (work / (language + ('.ts' if language == 'typescript' else '.mjs'))).write_text(generate_client_module([endpoint], language), encoding='utf-8')
        script = '''
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const ts = createRequire(import.meta.url)(COMPILER);
const source = fs.readFileSync('typescript.ts', 'utf8');
const result = ts.transpileModule(source, {compilerOptions: {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022}, reportDiagnostics: true});
assert.equal(result.diagnostics.length, 0);
fs.writeFileSync('typescript.mjs', result.outputText);
for (const language of ['javascript', 'typescript']) {
  const module = await import('./' + language + '.mjs');
  globalThis.fetch = async (url, options) => {
assert.equal(url, EXPECTED_URL);
assert.equal(options.method, 'POST');
assert.equal(options.body, '{"value":1}');
assert.equal(options.signal.aborted, false);
return {ok: true, status: 200, text: async () => '{"ok":true}'};
  };
  assert.deepEqual(await module.users_list('https://example.test', {value: 1}), {status: 200, data: {ok: true}});
  globalThis.fetch = (_url, options) => new Promise((_resolve, reject) => {
options.signal.addEventListener('abort', () => reject(new Error('cancelled by timeout')), {once: true});
  });
  await assert.rejects(module.users_list('https://example.test'), /cancelled by timeout/);
}
console.log('both client languages execute and cancel');
'''.replace('COMPILER', json.dumps(str(compiler))).replace('EXPECTED_URL', json.dumps('https://example.test' + endpoint['path']))
        probe = work / 'probe.mjs'
        probe.write_text(script, encoding='utf-8')
        run_bounded([node, str(probe)], cwd=work, timeout=15, log_path=work / 'client.log', environment=dict(os.environ))
        self.assertIn('both client languages execute and cancel', (work / 'client.log').read_text(encoding='utf-8'))

    def test_multi_file_save_restores_definition_when_generated_code_write_fails(self):
        work = self.temp / 'save'
        work.mkdir()
        definition, code = work / 'api/endpoints.json', work / 'src/generated_api.py'
        definition.parent.mkdir()
        definition.write_bytes(b'[]\n')
        replace = os.replace
        def fail_code(source, target):
            if Path(target) == code:
                raise OSError('injected generated-file write failure')
            replace(source, target)
        with patch('pcide.ui.platform_dialogs.os.replace', side_effect=fail_code):
            with self.assertRaises(OSError):
                atomic_files(work, {definition: b'[{}]\n', code: b'# generated by PCIDE\n'})
        self.assertEqual(definition.read_bytes(), b'[]\n')
        self.assertFalse(code.exists())
