def atomic_files(root, files, allow_generated_overwrite=False):
    """Validate every target and preserve previous bytes if a later write fails."""
    root = root.resolve()
    previous = {}
    for path, value in files.items():
        if not path.resolve().is_relative_to(root) or path.is_symlink():
            raise ValueError('保存路径必须在当前工程内')
        previous[path] = path.read_bytes() if path.is_file() else None
        if path.suffix in {'.py', '.js', '.ts'} and previous[path] is not None:
            owned = previous[path].startswith((b'# generated by PCIDE', b'// generated by PCIDE'))
            if not owned and not allow_generated_overwrite:
                raise ValueError(f'{path.name} 已存在且不是 IDE 生成文件；请改名，或勾选“替换已有生成代码”后保存')
    written = []
    try:
        for path, value in files.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, temporary = tempfile.mkstemp(prefix='.' + path.name, suffix='.tmp', dir=path.parent)
            try:
                with os.fdopen(fd, 'wb') as handle:
                    handle.write(value)
                    handle.flush()
                    os.fsync(handle.fileno())
                os.replace(temporary, path)
                written.append(path)
            finally:
                if Path(temporary).exists():
                    Path(temporary).unlink()
    except BaseException:
        for path in reversed(written):
            if previous[path] is None:
                path.unlink()
            else:
                path.write_bytes(previous[path])
        raise


class DocumentDesignerDialog(QDialog):
    source_relative = ''
    title = ''
    description = ''

    def __init__(self, project, parent=None):
        super().__init__(parent)
        self.project = project
        self.setWindowTitle(self.title)
        self.resize(980, 700)
        layout = QVBoxLayout(self)
        note = QLabel(self.description)
        note.setWordWrap(True)
        layout.addWidget(note)
        self.tabs = QTabWidget()
        self.designer = self.build_form()
        self.tabs.addTab(self.designer, '结构化编辑')
        self.editor = QPlainTextEdit()
        self.tabs.addTab(self.editor, 'JSON 源文')
        self.preview = QPlainTextEdit()
        self.preview.setReadOnly(True)
        self.tabs.addTab(self.preview, '生成预览')
        layout.addWidget(self.tabs, 1)
        options = QHBoxLayout()
        self.generate = QCheckBox('保存时生成代码')
        self.generate.setEnabled(self.code_supported())
        self.generate.setChecked(self.code_supported())
        self.generate.setToolTip(self.generation_description())
        self.overwrite = QCheckBox('替换已有生成代码')
        self.overwrite.setToolTip('只有覆盖非 IDE 生成的同名文件时才需要勾选；JSON 定义和代码在校验后一起保存')
        options.addWidget(self.generate)
        options.addWidget(self.overwrite)
        options.addWidget(QLabel(self.generation_description()), 1)
        layout.addLayout(options)
        self.error = QLabel()
        self.error.setWordWrap(True)
        layout.addWidget(self.error)
        self.buttons = dialog_buttons(QDialogButtonBox.StandardButton.Save | QDialogButtonBox.StandardButton.Cancel)
        self.buttons.accepted.connect(self.save)
        self.buttons.rejected.connect(self.reject)
        layout.addWidget(self.buttons)
        path = project.root / self.source_relative
        initial = json.dumps(self.default_value(), ensure_ascii=False, indent=2)
        if path.is_file():
            if not path.resolve().is_relative_to(project.root.resolve()) or path.stat().st_size > 2 * 1024 * 1024:
                raise ValueError('定义文件越界或超过 2 MiB')
            initial = path.read_text(encoding='utf-8')
        self.editor.setPlainText(initial)
        try:
            self.load_form(self.normalise(json.loads(initial)))
        except (ValueError, TypeError) as exc:
            self.load_form(self.default_value())
            self.tabs.setCurrentIndex(1)
            self.error.setText(str(exc))
        self.active_tab = self.tabs.currentIndex()
        self.tabs.currentChanged.connect(self.switch_tab)

    def code_language(self):
        language = self.project.manifest['language']
        return 'python' if language == 'zhxb' else language

    def code_supported(self):
        return self.code_language() in {'python', 'javascript', 'typescript'}

    def switch_tab(self, index):
        try:
            if self.active_tab == 1:
                model = self.normalise(json.loads(self.editor.toPlainText()))
                self.load_form(model)
            else:
                model = self.read_form()
                self.editor.setPlainText(json.dumps(model, ensure_ascii=False, indent=2))
            if index == 2:
                self.preview.setPlainText(self.preview_code(self.normalise(model)))
            self.error.clear()
            self.active_tab = index
        except (ValueError, TypeError) as exc:
            self.error.setText(str(exc))
            self.tabs.blockSignals(True)
            self.tabs.setCurrentIndex(self.active_tab)
            self.tabs.blockSignals(False)

    def save(self):
        try:
            model = self.normalise(json.loads(self.editor.toPlainText()) if self.active_tab == 1 else self.read_form())
            files = {self.project.root / self.source_relative:
                     (json.dumps(model, ensure_ascii=False, indent=2) + '\n').encode('utf-8')}
            if self.generate.isChecked() and self.code_supported():
                target, source = self.generated_file(model)
                files[target] = source.encode('utf-8')
            atomic_files(self.project.root, files, self.overwrite.isChecked())
            self.accept()
        except (ValueError, TypeError, OSError) as exc:
            self.error.setText(str(exc))


class DatabaseDesignerDialog(DocumentDesignerDialog):
    source_relative = 'database/schema.json'
    title = '数据库设计器'
    description = '编辑 SQLite 表、字段、主键、空值、默认值和索引。JSON 源文与表格同步；生成预览显示实际 CRUD SQL。默认值使用 JSON 标量，留空表示无默认值。'

    def default_value(self):
        return {'version': 1, 'tables': [{'name': 'users', 'columns': [
            {'name': 'id', 'type': 'INTEGER', 'primary_key': True, 'nullable': False},
            {'name': 'name', 'type': 'TEXT'}], 'indexes': ['name']}]}

    def code_supported(self):
        return self.code_language() == 'python'

    def generation_description(self):
        return 'Python/中文工程可生成 src/generated_database.py；其他语言保存定义并使用 CRUD SQL。'

    def normalise(self, value):
        return validate_schema(value)

    def build_form(self):
        host = QWidget()
        layout = QVBoxLayout(host)
        split = QSplitter()
        left = QWidget()
        left_layout = QVBoxLayout(left)
        self.table_list = QListWidget()
        left_layout.addWidget(QLabel('数据库表'))
        left_layout.addWidget(self.table_list, 1)
        bar = QHBoxLayout()
        for label, callback in (('添加表', self.add_table), ('删除表', self.delete_table)):
            button = QPushButton(label)
            button.clicked.connect(callback)
            bar.addWidget(button)
        left_layout.addLayout(bar)
        right = QWidget()
        right_layout = QVBoxLayout(right)
        self.table_name = QLineEdit()
        self.table_name.setPlaceholderText('表名：字母、数字和下划线')
        right_layout.addWidget(self.table_name)
        self.columns = QTableWidget(0, 6)
        self.columns.setHorizontalHeaderLabels(['字段名', 'SQLite 类型', '允许空', '主键', '默认值（JSON）', '建立索引'])
        self.columns.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        self.columns.setAlternatingRowColors(True)
        right_layout.addWidget(self.columns, 1)
        bar = QHBoxLayout()
        for label, callback in (('添加字段', self.add_column), ('删除字段', self.delete_column)):
            button = QPushButton(label)
            button.clicked.connect(callback)
            bar.addWidget(button)
        right_layout.addLayout(bar)
        split.addWidget(left)
        split.addWidget(right)
        split.setSizes([220, 700])
        layout.addWidget(split)
        self.tables = []
        self.current_table = -1
        self.table_list.currentRowChanged.connect(self.select_table)
        self.table_name.textEdited.connect(lambda value: self.table_list.currentItem().setText(value) if self.table_list.currentItem() else None)
        return host

    def commit_table(self):
        if not 0 <= self.current_table < len(self.tables):
            return
        columns, indexes = [], []
        for row in range(self.columns.rowCount()):
            name = self.columns.item(row, 0).text().strip()
            default = self.columns.item(row, 4).text().strip()
            columns.append({'name': name, 'type': self.columns.cellWidget(row, 1).currentText(),
                            'nullable': self.columns.cellWidget(row, 2).isChecked(),
                            'primary_key': self.columns.cellWidget(row, 3).isChecked(),
                            'default': json.loads(default) if default else None})
            if self.columns.cellWidget(row, 5).isChecked():
                indexes.append(name)
        self.tables[self.current_table] = {'name': self.table_name.text().strip(), 'columns': columns, 'indexes': indexes}

    def select_table(self, row):
        try:
            self.commit_table()
        except ValueError as exc:
            self.error.setText('默认值不是有效 JSON 标量：' + str(exc))
            self.table_list.blockSignals(True)
            self.table_list.setCurrentRow(self.current_table)
            self.table_list.blockSignals(False)
            return
        self.current_table = row
        self.columns.setRowCount(0)
        self.table_name.setEnabled(row >= 0)
        if 0 <= row < len(self.tables):
            table = self.tables[row]
            self.table_name.setText(table['name'])
            for column in table['columns']:
                self.add_column(column, column['name'] in table.get('indexes', []))
        else:
            self.table_name.clear()

    def load_form(self, model):
        self.tables = copy.deepcopy(model['tables'])
        self.current_table = -1
        self.table_list.blockSignals(True)
        self.table_list.clear()
        self.table_list.addItems([table['name'] for table in self.tables])
        self.table_list.blockSignals(False)
        self.table_list.setCurrentRow(0 if self.tables else -1)
        if not self.tables:
            self.select_table(-1)

    def read_form(self):
        self.commit_table()
        return {'version': 1, 'tables': copy.deepcopy(self.tables)}

    def add_table(self):
        try:
            self.commit_table()
        except ValueError as exc:
            self.error.setText(str(exc))
            return
        number = 1
        names = {table['name'] for table in self.tables}
        while f'table{number}' in names:
            number += 1
        model = self.read_form()
        model['tables'].append({'name': f'table{number}', 'columns': [{'name': 'id', 'type': 'INTEGER', 'primary_key': True, 'nullable': False}], 'indexes': []})
        self.load_form(model)
        self.table_list.setCurrentRow(len(self.tables) - 1)

    def delete_table(self):
        row = self.table_list.currentRow()
        if row >= 0:
            self.tables.pop(row)
            self.load_form({'version': 1, 'tables': self.tables})

    def add_column(self, column=None, indexed=False):
        if not isinstance(column, dict):
            column = {'name': f'field{self.columns.rowCount() + 1}', 'type': 'TEXT'}
        row = self.columns.rowCount()
        self.columns.insertRow(row)
        self.columns.setItem(row, 0, QTableWidgetItem(column['name']))
        kind = QComboBox()
        kind.addItems(['TEXT', 'INTEGER', 'REAL', 'BLOB', 'NUMERIC'])
        kind.setCurrentText(column.get('type', 'TEXT'))
        self.columns.setCellWidget(row, 1, kind)
        for index, checked in ((2, column.get('nullable', True)), (3, column.get('primary_key', False)), (5, indexed)):
            check = QCheckBox()
            check.setChecked(checked)
            self.columns.setCellWidget(row, index, check)
        default = column.get('default')
        self.columns.setItem(row, 4, QTableWidgetItem('' if default is None else json.dumps(default, ensure_ascii=False)))
        self.columns.setColumnWidth(0, 130)
        self.columns.setColumnWidth(1, 110)
        self.columns.setColumnWidth(2, 70)
        self.columns.setColumnWidth(3, 65)
        self.columns.setColumnWidth(4, 180)
        self.columns.setColumnWidth(5, 90)

    def delete_column(self):
        row = self.columns.currentRow()
        if row >= 0:
            self.columns.removeRow(row)

    def generated_file(self, model):
        return self.project.root / 'src/generated_database.py', generate_python_module(model)

    def preview_code(self, model):
        sections = []
        for table in model['tables']:
            contract = Table(table['name'], tuple(Column(**column) for column in table['columns']), tuple(table['indexes']))
            sections.append('-- 表：' + table['name'] + '\n' + '\n'.join(f'-- {kind}\n{sql};' for kind, sql in generate_crud(contract).items()))
        if self.code_supported():
            sections.append('# Python CRUD 元数据\n' + generate_python_module(model))
        return '\n\n'.join(sections)


class ApiCenterDialog(DocumentDesignerDialog):
    source_relative = 'api/endpoints.json'
    title = 'API 中心'
    description = '编辑接口标识、名称、协议、方法、路径、超时和响应声明。当前生成 HTTP/HTTPS 客户端；WebSocket/TCP/UDP/MQTT 保存声明，调用需要外部 transport。Python/中文客户端超时上限 60 秒，JS/TS 使用 fetch 与超时取消；响应声明暂不改变现有自动解析行为。'

    def default_value(self):
        return [{'id': 'users.list', 'name': '用户列表', 'method': 'GET', 'path': '/v1/users', 'protocol': 'https'}]

    def generation_description(self):
        return 'Python/中文/JS/TS 工程可生成 src/generated_api；其他语言只保存接口定义。'

    def normalise(self, value):
        if not isinstance(value, list) or len(value) > 500:
            raise ValueError('接口必须是最多 500 项的数组')
        endpoints = [validate_endpoint(item) for item in value]
        if len({item.id for item in endpoints}) != len(endpoints):
            raise ValueError('接口 ID 不能重复')
        names = [re.sub(r'[^A-Za-z0-9_]', '_', item.id) for item in endpoints]
        if len(set(names)) != len(names):
            raise ValueError('接口 ID 转换后的函数名重复，请使用不同标识')
        return [item.__dict__ for item in endpoints]

    def build_form(self):
        host = QWidget()
        layout = QVBoxLayout(host)
        bar = QHBoxLayout()
        for label, callback in (('添加接口', self.add_endpoint), ('复制接口', self.duplicate_endpoint), ('删除接口', self.delete_endpoint)):
            button = QPushButton(label)
            button.clicked.connect(callback)
            bar.addWidget(button)
        bar.addStretch()
        layout.addLayout(bar)
        self.table = QTableWidget(0, 7)
        self.table.setHorizontalHeaderLabels(['接口标识', '名称', '协议', '方法', '路径', '超时（秒）', '响应声明'])
        self.table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        self.table.setAlternatingRowColors(True)
        layout.addWidget(self.table, 1)
        return host

    def load_form(self, model):
        self.table.setRowCount(0)
        for endpoint in model:
            self.add_endpoint(endpoint)

    def add_endpoint(self, endpoint=None):
        if not isinstance(endpoint, dict):
            used = {self.table.item(row, 0).text() for row in range(self.table.rowCount())}
            number = self.table.rowCount() + 1
            while f'api{number}' in used:
                number += 1
            endpoint = {'id': f'api{number}', 'name': '新接口', 'protocol': 'https', 'method': 'GET', 'path': '/'}
        row = self.table.rowCount()
        self.table.insertRow(row)
        for index, key in ((0, 'id'), (1, 'name'), (4, 'path')):
            self.table.setItem(row, index, QTableWidgetItem(endpoint[key]))
        for index, key, choices in ((2, 'protocol', ['http', 'https', 'websocket', 'tcp', 'udp', 'mqtt']),
                                    (3, 'method', ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS', 'SEND', 'RECEIVE']),
                                    (6, 'response_type', ['json', 'text', 'bytes'])):
            box = QComboBox()
            box.addItems(choices)
            box.setCurrentText(endpoint.get(key, choices[0]))
            self.table.setCellWidget(row, index, box)
        timeout = QDoubleSpinBox()
        timeout.setRange(0.001, 300)
        timeout.setDecimals(3)
        timeout.setValue(endpoint.get('timeout_seconds', 30))
        self.table.setCellWidget(row, 5, timeout)
        for index, width in ((0, 150), (1, 140), (2, 100), (3, 95), (4, 210), (5, 100), (6, 110)):
            self.table.setColumnWidth(index, width)

    def read_form(self):
        return [{'id': self.table.item(row, 0).text().strip(), 'name': self.table.item(row, 1).text().strip(),
                 'protocol': self.table.cellWidget(row, 2).currentText(), 'method': self.table.cellWidget(row, 3).currentText(),
                 'path': self.table.item(row, 4).text().strip(), 'timeout_seconds': self.table.cellWidget(row, 5).value(),
                 'response_type': self.table.cellWidget(row, 6).currentText()} for row in range(self.table.rowCount())]

    def duplicate_endpoint(self):
        row = self.table.currentRow()
        if row >= 0:
            endpoint = self.read_form()[row]
            used = {self.table.item(index, 0).text() for index in range(self.table.rowCount())}
            identity, number = endpoint['id'] + '.copy', 2
            while identity in used:
                identity = endpoint['id'] + f'.copy{number}'
                number += 1
            endpoint['id'] = identity
            self.add_endpoint(endpoint)

    def delete_endpoint(self):
        row = self.table.currentRow()
        if row >= 0:
            self.table.removeRow(row)

    def generated_file(self, model):
        language = self.code_language()
        extension = {'python': '.py', 'javascript': '.js', 'typescript': '.ts'}[language]
        prefix = '# ' if language == 'python' else '// '
        source = prefix + 'generated by PCIDE API center\n' + generate_client_module(model, language)
        return self.project.root / ('src/generated_api' + extension), source

    def preview_code(self, model):
        if self.code_supported():
            return self.generated_file(model)[1]
        return '当前工程不生成脚本客户端；以下为接口声明。\n\n' + json.dumps(model, ensure_ascii=False, indent=2)
